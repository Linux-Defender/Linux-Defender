#!/usr/bin/env python3
"""Generate (or --check) a human-review report for the gettext catalogs.

Automated checks already prove the catalogs are extractable, complete, and
well-formed. This report isolates the one thing automation cannot decide:
English text left identical in a non-English catalog, which may be untranslated
prose or a legitimate product/technical literal. A human translator reviews the
candidates; no translation is invented here.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PO = ROOT / "po"
REPORT = PO / "TRANSLATION-REVIEW.md"
LOCALES = [l.strip() for l in (PO / "LINGUAS").read_text(encoding="utf-8").splitlines()
           if l.strip() and not l.strip().startswith("#")]
PROTECTED = re.compile(
    r"clamav|clamtk|virustotal|urlscan|urlhaus|linux defender|gtk|dbus|systemd|"
    r"polkit|yal?ra|eicar|appimage|flatpak|snap|deb|rpm|aur|wayland|sway",
    re.I,
)


def statistics(locale: str) -> str:
    result = subprocess.run(
        ["msgfmt", "--statistics", "--check-format", "-o", "/dev/null", str(PO / f"{locale}.po")],
        capture_output=True, text=True,
    )
    return (result.stdout + result.stderr).strip().splitlines()[-1] if result.returncode == 0 else "msgfmt failed"


def po_string(lines: list[str], index: int, prefix: str) -> tuple[str, int]:
    """Decode one msgid/msgstr value, including multi-line continuations."""
    first = lines[index][len(prefix):]
    parts: list[str] = []
    if first.startswith('"'):
        parts.append(first[1:-1])
        index += 1
        while index < len(lines) and lines[index].startswith('"'):
            parts.append(lines[index][1:-1])
            index += 1
    return "".join(parts), index


def identical_candidates(locale: str) -> list[str]:
    text = (PO / f"{locale}.po").read_text(encoding="utf-8", errors="replace")
    lines = text.split("\n")
    identical: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("msgid "):
            msgid, index = po_string(lines, index, "msgid ")
            # Skip msgctxt and msgid_plural blocks safely.
            while index < len(lines) and not lines[index].startswith("msgstr"):
                index += 1
            if index >= len(lines):
                break
            msgstr, index = po_string(lines, index, "msgstr ")
            if (
                msgid
                and msgid == msgstr
                and len(msgid) >= 30
                and not PROTECTED.search(msgid)
            ):
                identical.append(msgid.replace('\\"', '"'))
            continue
        index += 1
    return sorted(set(identical))


def generate() -> str:
    lines = [
        "# Translation review report",
        "",
        "<!-- Generated by scripts/generate-translation-review.py. Do not edit by hand. -->",
        "",
        "Automated validation (`update-pot.sh --check`, `check-potfiles.sh`,",
        "`check-translations.sh`, `msgfmt -c`, `msgcmp`) passes for all active",
        "catalogs. This report lists long English strings that are still identical",
        "in a non-English catalog. Some are legitimate protected literals; a human",
        "translator decides. No machine translation is applied by this script. "
        + "Where an msgid matches an upstream MIT ClamUI catalog exactly, the human "
        + "translation from that catalog is adopted and recorded in the audit ledger; "
        + "the remaining candidates are new Linux Defender strings with no upstream source.",
        "",
        "| Locale | msgfmt statistics | Long identical strings |",
        "| --- | --- | ---: |",
    ]
    for locale in LOCALES:
        if locale == "en":
            lines.append(f"| {locale} | {statistics(locale)} | baseline |")
            continue
        candidates = identical_candidates(locale)
        lines.append(f"| {locale} | {statistics(locale)} | {len(candidates)} |")
    lines.append("")
    for locale in LOCALES:
        if locale == "en":
            continue
        candidates = identical_candidates(locale)
        lines.append(f"## {locale}")
        lines.append("")
        if not candidates:
            lines.append("No long identical strings found.")
        else:
            for msgid in candidates[:40]:
                lines.append(f"- `{msgid}`")
            if len(candidates) > 40:
                lines.append(f"- … {len(candidates) - 40} more")
        lines.append("")
    lines.append("## Review procedure")
    lines.append("")
    lines.append("For each candidate, keep it unchanged if it is a protected product, command,")
    lines.append("file, or technical literal. Otherwise translate the source string in the")
    lines.append("catalog, run `msgfmt -c` and `msgcmp`, then regenerate this report with")
    lines.append("`python3 scripts/generate-translation-review.py` and commit the change.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    content = generate()
    if "--check" in sys.argv:
        actual = REPORT.read_text(encoding="utf-8") if REPORT.exists() else ""
        if actual != content:
            print("Translation review report is stale. Run: python3 scripts/generate-translation-review.py", file=sys.stderr)
            return 1
        print("Translation review report OK")
        return 0
    REPORT.write_text(content, encoding="utf-8")
    print(f"Wrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
