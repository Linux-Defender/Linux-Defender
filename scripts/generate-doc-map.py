#!/usr/bin/env python3
"""Generate (or --check) the complete documentation map.

docs/DOC-MAP.md links every tracked Markdown/MDX document from one place, so
nothing can be written and then forgotten. Run this after adding or removing a
doc; `check-all.sh` runs it in --check mode and fails on drift.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "docs/DOC-MAP.md"
SKIP_DIRS = {".agents", "node_modules", "target", "dist", "vendor", ".git"}
SKIP_FILES = {"DOC-MAP.md"}


def tracked_docs() -> list[str]:
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True)
    return sorted(p for p in out.stdout.splitlines()
                  if p.endswith((".md", ".mdx"))
                  and not any(part in SKIP_DIRS for part in Path(p).parts)
                  and Path(p).name not in SKIP_FILES)


def group(paths: list[str]) -> list[tuple[str, list[str]]]:
    groups: dict[str, list[str]] = {
        "Root guidance and release information": [],
        "Internal development and research docs": [],
        "Published website documentation": [],
        "Coding-agent tooling": [],
    }
    for p in paths:
        if p.startswith("website/"):
            groups["Published website documentation"].append(p)
        elif p.startswith("docs/"):
            groups["Internal development and research docs"].append(p)
        elif p.startswith(".claude/"):
            groups["Coding-agent tooling"].append(p)
        else:
            groups["Root guidance and release information"].append(p)
    return [(name, items) for name, items in groups.items() if items]


def generate() -> str:
    lines = [
        "# Documentation map",
        "",
        "<!-- Generated by scripts/generate-doc-map.py. Do not edit by hand. -->",
        "",
        "Every tracked Markdown/MDX document in this repository is linked from",
        "this page. Folder indexes (`docs/README.md`, `docs/revival/README.md`,",
        "and the Starlight sidebar) provide deeper navigation; this map is the",
        "complete cross-check that nothing is forgotten or orphaned.",
        "",
    ]
    for title, paths in group(tracked_docs()):
        lines.append(f"## {title}")
        lines.append("")
        for p in paths:
            rel = "../" + p if not p.startswith("docs/") else p[len("docs/"):]
            label = p.replace(".mdx", "").replace(".md", "")
            lines.append(f"- [{label}]({rel})")
        lines.append("")
    lines.append("## Regenerating")
    lines.append("")
    lines.append("Run `python3 scripts/generate-doc-map.py` after adding, moving, or")
    lines.append("removing a document. `bash scripts/check-all.sh` verifies that this")
    lines.append("map matches the repository, so a new document cannot be forgotten.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    content = generate()
    if "--check" in sys.argv:
        actual = MAP.read_text(encoding="utf-8") if MAP.exists() else ""
        if actual != content:
            print("Doc map is stale. Run: python3 scripts/generate-doc-map.py", file=sys.stderr)
            return 1
        print("Doc map OK: every tracked document is linked")
        return 0
    MAP.write_text(content, encoding="utf-8")
    print(f"Wrote {MAP.relative_to(ROOT)} with {len(tracked_docs())} documents")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
